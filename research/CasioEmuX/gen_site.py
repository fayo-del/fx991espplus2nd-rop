#!/usr/bin/env python3
"""gen_site.py — regenerate site/payload.js (embedded data for the payload-entry helper site).

Source of truth: keygen.py encoding of the real03 payload (md5 a658df02...).
Run:  cd research/CasioEmuX && python3 gen_site.py
Output: ../../site/payload.js  (PAYLOAD_HEX, PAYLOAD_MD5, RECIPE, TRIGGER, STEPS)
"""
import hashlib, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import keygen

PAYLOAD_HEX = ("22370e4dbd8b0c6e014d503a0e4d66300e4dee8d0c47014df24e014d0e0e0e0e"
               "66300e4da48dde750e4d0e0e66300e4da48dde75a48da24c014d0e4d0e4d22370e"
               "30bd8b0c6e014da84a0e4dc2490e4d0cf892420e4da24c014d22370e4dbd8b202b0e4d")

def slim(steps):
    out = []
    for s in steps:
        e = {"kind": s["kind"]}
        for k in ("mod", "code", "name", "note", "byte", "conf", "seed", "walk"):
            if k in s:
                e[k] = s[k]
        if s["kind"] == "template":
            e["chords"] = s["chords"]
            e["bytes"] = list(s["bytes"])
        out.append(e)
    return out


def main():
    payload = bytes.fromhex(PAYLOAD_HEX)
    assert hashlib.md5(payload).hexdigest() == "a658df02158fd362305b1cc2a559a806", "payload drifted"
    tabs = keygen.load_tables()
    steps, report, direct = keygen.encode(payload, tabs)
    recipe = [{"code": c, "name": l} for c, l in keygen.RECIPE]
    trigger = [{"code": c, "name": l} for c, l in keygen.TRIGGER]
    data = {
        "PAYLOAD_HEX": PAYLOAD_HEX,
        "PAYLOAD_MD5": hashlib.md5(payload).hexdigest(),
        "PRESSES_PAYLOAD": keygen.keypress_count(steps),
        "RECIPE": recipe,
        "TRIGGER": trigger,
        "STEPS": slim(steps),
    }
    site = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "site"))
    os.makedirs(site, exist_ok=True)
    with open(os.path.join(site, "payload.js"), "w") as f:
        f.write("// generated by research/CasioEmuX/gen_site.py — do not edit\n")
        f.write("window.SITE_DATA = " + json.dumps(data) + ";\n")
    n_walk = sum(1 for s in steps if s.get("walk"))
    n_wait = sum(1 for s in steps if s["kind"] == "wait")
    print(f"wrote {site}/payload.js: {len(steps)} steps, {keygen.keypress_count(steps)} payload presses, "
          f"{n_walk} walk arrows, {n_wait} flash-waits, md5 ok")

if __name__ == "__main__":
    main()
